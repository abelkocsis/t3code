/**
 * The panel generates only on an explicit act: the first open of a day with
 * work and no stored summary, or the Regenerate button. Browsing other days
 * shows what is stored and offers a button, so history costs no tokens.
 */
import {
  DndContext,
  PointerSensor,
  closestCenter,
  useSensor,
  useSensors,
  type DragEndEvent,
} from "@dnd-kit/core";
import { restrictToParentElement, restrictToVerticalAxis } from "@dnd-kit/modifiers";
import { SortableContext, useSortable, verticalListSortingStrategy } from "@dnd-kit/sortable";
import { CSS } from "@dnd-kit/utilities";
import { hasStandupEdits } from "@t3tools/contracts";
import type { EnvironmentId, StandupItem, StandupLearnProposal } from "@t3tools/contracts";
import {
  ChevronLeft,
  ChevronRight,
  Copy,
  GraduationCap,
  GripVertical,
  ListChecks,
  Pencil,
  Plus,
  RefreshCw,
  Sparkles,
  Undo2,
  X,
} from "lucide-react";
import { useEffect, useRef, useState } from "react";

import { Button } from "~/components/ui/button";
import { Checkbox } from "~/components/ui/checkbox";
import {
  Dialog,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogPanel,
  DialogPopup,
  DialogTitle,
} from "~/components/ui/dialog";
import { Input } from "~/components/ui/input";
import { ScrollArea } from "~/components/ui/scroll-area";
import { Toggle, ToggleGroup } from "~/components/ui/toggle-group";
import { Tooltip, TooltipPopup, TooltipTrigger } from "~/components/ui/tooltip";
import { cn } from "~/lib/utils";
import { formatStandupHtml, useStandup, type InstructOutcome } from "~/state/standup";

const EMPTY_ITEMS: readonly StandupItem[] = [];

/** Steps a `YYYY-MM-DD` day, which is all the panel's arrows ever need. */
function shiftDay(day: string, delta: number): string {
  const [year = 0, month = 1, date = 1] = day.split("-").map(Number);
  return new Date(Date.UTC(year, month - 1, date + delta)).toISOString().slice(0, 10);
}

function formatDayLabel(day: string): string {
  const [year = 0, month = 1, date = 1] = day.split("-").map(Number);
  return new Date(Date.UTC(year, month - 1, date)).toLocaleDateString(undefined, {
    weekday: "short",
    day: "numeric",
    month: "short",
    timeZone: "UTC",
  });
}

function sameMembership(left: readonly StandupItem[], right: readonly StandupItem[]): boolean {
  if (left.length !== right.length) return false;
  const ids = new Set(left.map((item) => item.itemId));
  return right.every((item) => ids.has(item.itemId));
}

export function StandupPanel({ environmentId }: { environmentId: EnvironmentId | null }) {
  const standup = useStandup(environmentId);
  const { day, hasWork, summary, isLoading, isGenerating, generate } = standup;
  const [draft, setDraft] = useState("");
  const [inputMode, setInputMode] = useState<"add" | "ask">("add");
  const [copied, setCopied] = useState(false);
  /** The last model reply, with the day it belongs to so a day change clears it. */
  const [reply, setReply] = useState<(InstructOutcome & { day: string }) | null>(null);
  const [ruleRemembered, setRuleRemembered] = useState(false);
  const [learnProposals, setLearnProposals] = useState<readonly StandupLearnProposal[] | null>(
    null,
  );
  /**
   * The order the user just dragged to, shown until the server echoes it.
   * Without it the list snaps back to the stored order for one round trip.
   */
  const [draggedOrder, setDraggedOrder] = useState<readonly StandupItem[] | null>(null);

  const serverItems = summary?.items ?? EMPTY_ITEMS;

  // A local order only survives while the same bullets are on screen. Adding,
  // removing or regenerating changes the membership, and the server's order is
  // then the only correct one.
  let items = serverItems;
  if (draggedOrder !== null && sameMembership(serverItems, draggedOrder)) {
    const byId = new Map(serverItems.map((item) => [item.itemId, item]));
    items = draggedOrder.map((item) => byId.get(item.itemId) ?? item);
  }

  // One automatic generation per day, and only for a day that holds work and
  // has never been generated. Without the guard, a failed run would retry on
  // every render and spend tokens the user never asked for.
  const autoGeneratedDays = useRef(new Set<string>());
  const draftInputRef = useRef<HTMLInputElement>(null);
  // oxlint-disable-next-line t3code/no-unreasoned-state-sync -- starts a server generation once per day after the state query lands; the trigger is the loaded state, not a user action
  useEffect(() => {
    if (day === null || summary !== null || !hasWork || isLoading || isGenerating) return;
    if (autoGeneratedDays.current.has(day)) return;
    autoGeneratedDays.current.add(day);
    void generate();
  }, [day, generate, hasWork, isGenerating, isLoading, summary]);

  // Both flavors go out together, so Slack reads the list from the HTML while
  // a terminal or editor still gets the plain bullets.
  const copy = async () => {
    const html = formatStandupHtml(items);
    if (navigator.clipboard.write && typeof ClipboardItem !== "undefined") {
      await navigator.clipboard.write([
        new ClipboardItem({
          "text/plain": new Blob([standup.text], { type: "text/plain" }),
          "text/html": new Blob([html], { type: "text/html" }),
        }),
      ]);
    } else {
      await navigator.clipboard.writeText(standup.text);
    }
    await standup.save();
    setCopied(true);
  };

  // oxlint-disable-next-line t3code/no-unreasoned-state-sync -- a timer that clears the Copied label
  useEffect(() => {
    if (!copied) return;
    const timer = setTimeout(() => setCopied(false), 2_000);
    return () => clearTimeout(timer);
  }, [copied]);

  // A short distance keeps a plain click on the handle from starting a drag,
  // and keeps the bullet text selectable.
  const sensors = useSensors(useSensor(PointerSensor, { activationConstraint: { distance: 6 } }));

  const handleDragEnd = (event: DragEndEvent) => {
    const { active, over } = event;
    if (!over || active.id === over.id) return;
    const from = items.findIndex((item) => item.itemId === active.id);
    const to = items.findIndex((item) => item.itemId === over.id);
    if (from === -1 || to === -1) return;
    const next = [...items];
    const [moved] = next.splice(from, 1);
    if (!moved) return;
    next.splice(to, 0, moved);
    setDraggedOrder(next);
    void standup.reorderItems(next);
  };

  const keptCount = items.filter((item) => !item.excluded).length;
  const sortableIds = items.map((item) => item.itemId);
  const busy = isLoading || isGenerating;
  const shownReply = reply !== null && reply.day === day ? reply : null;
  const canLearn = summary !== null && hasStandupEdits(items) && !standup.isLearning;

  const submitDraft = async () => {
    const text = draft.trim();
    if (text.length === 0) return;
    if (inputMode === "add") {
      setDraft("");
      await standup.addItem(text);
      return;
    }
    if (day === null) return;
    const outcome = await standup.instruct(text);
    if (outcome === null) return;
    setDraft("");
    setRuleRemembered(false);
    setReply({ ...outcome, day });
  };

  const openLearn = async () => {
    const proposals = await standup.learn();
    if (proposals !== null) setLearnProposals(proposals);
  };

  return (
    <div className="flex h-full flex-col">
      <div className="flex shrink-0 items-center gap-1 border-b px-2 py-1.5">
        <Button
          variant="ghost"
          size="icon-sm"
          aria-label="Previous day"
          disabled={day === null}
          onClick={() => day !== null && standup.showDay(shiftDay(day, -1))}
        >
          <ChevronLeft className="size-4" />
        </Button>
        <span className="min-w-0 flex-1 truncate text-center font-medium text-sm">
          {day !== null
            ? formatDayLabel(day)
            : isLoading
              ? "Finding the last day with work..."
              : "No work recorded yet"}
        </span>
        <Button
          variant="ghost"
          size="icon-sm"
          aria-label="Next day"
          disabled={day === null}
          onClick={() => day !== null && standup.showDay(shiftDay(day, 1))}
        >
          <ChevronRight className="size-4" />
        </Button>
        <Tooltip>
          <TooltipTrigger render={<span className="flex shrink-0" />}>
            <Button
              variant="ghost"
              size="icon-sm"
              aria-label="Regenerate the summary"
              disabled={day === null || isGenerating || !hasWork}
              onClick={() => void generate()}
            >
              {/* A finite spin: it stops the moment the request settles. */}
              <RefreshCw className={cn("size-4", busy && "animate-spin")} />
            </Button>
          </TooltipTrigger>
          <TooltipPopup side="bottom">Regenerate the summary</TooltipPopup>
        </Tooltip>
        <Tooltip>
          <TooltipTrigger render={<span className="flex shrink-0" />}>
            <Button
              variant="ghost"
              size="icon-sm"
              aria-label="Learn from my edits"
              disabled={!canLearn}
              onClick={() => void openLearn()}
            >
              <GraduationCap className={cn("size-4", standup.isLearning && "animate-pulse")} />
            </Button>
          </TooltipTrigger>
          <TooltipPopup side="bottom">
            {canLearn || standup.isLearning
              ? "Learn from my edits"
              : "Edit, drop or add a bullet first"}
          </TooltipPopup>
        </Tooltip>
      </div>

      <ScrollArea className="min-h-0 flex-1">
        <div className="flex flex-col gap-px p-2">
          {standup.error !== null ? (
            <p className="px-1 py-2 text-destructive text-sm">{standup.error}</p>
          ) : null}

          {isGenerating ? (
            <p className="px-1 py-2 text-muted-foreground text-sm">Reading the day's work...</p>
          ) : isLoading && summary === null ? (
            <p className="px-1 py-2 text-muted-foreground text-sm">Loading the day...</p>
          ) : null}

          {!busy && summary === null && day !== null ? (
            hasWork ? (
              <Button
                variant="secondary"
                size="sm"
                className="mt-1"
                onClick={() => void generate()}
              >
                <ListChecks className="size-4" />
                Write the summary for this day
              </Button>
            ) : (
              <p className="px-1 py-2 text-muted-foreground text-sm">
                Nothing was recorded on this day.
              </p>
            )
          ) : null}

          <DndContext
            sensors={sensors}
            collisionDetection={closestCenter}
            modifiers={[restrictToVerticalAxis, restrictToParentElement]}
            onDragEnd={handleDragEnd}
          >
            <SortableContext items={sortableIds} strategy={verticalListSortingStrategy}>
              {items.map((item) => (
                <StandupItemRow
                  key={item.itemId}
                  item={item}
                  onToggle={() => void standup.setItemExcluded(item.itemId, !item.excluded)}
                  onEdit={(text) => void standup.setItemText(item.itemId, text)}
                />
              ))}
            </SortableContext>
          </DndContext>
        </div>
      </ScrollArea>

      <div className="flex shrink-0 flex-col gap-2 border-t p-2">
        {standup.isInstructing ? (
          <p className="px-1 text-muted-foreground text-sm">Asking the model...</p>
        ) : shownReply !== null ? (
          <div className="flex flex-col gap-1 px-1 text-sm">
            <p className="whitespace-pre-wrap text-muted-foreground">{shownReply.reply}</p>
            <div className="flex flex-wrap items-center gap-1">
              {shownReply.changed && standup.canUndoInstruct ? (
                <Button
                  variant="ghost"
                  size="sm"
                  onClick={() => {
                    void standup.undoInstruct();
                    setReply(null);
                  }}
                >
                  <Undo2 className="size-3.5" />
                  Undo
                </Button>
              ) : null}
              {shownReply.suggestedRule !== null ? (
                <Button
                  variant="ghost"
                  size="sm"
                  disabled={ruleRemembered}
                  onClick={() => {
                    if (shownReply.suggestedRule === null) return;
                    void standup.addLearnings([shownReply.suggestedRule], "taught");
                    setRuleRemembered(true);
                  }}
                >
                  <GraduationCap className="size-3.5" />
                  {ruleRemembered ? "Remembered" : `Remember: ${shownReply.suggestedRule}`}
                </Button>
              ) : null}
            </div>
          </div>
        ) : null}
        <form
          className="flex items-center gap-1"
          onSubmit={(event) => {
            event.preventDefault();
            void submitDraft();
          }}
        >
          <ToggleGroup
            aria-label="What the box does"
            value={[inputMode]}
            onValueChange={(next) => {
              const value = next[0];
              if (value === "add" || value === "ask") setInputMode(value);
              // The toggle took focus. Without it, the next keystroke lands in the chat composer.
              draftInputRef.current?.focus();
            }}
          >
            <Toggle value="add" aria-label="Add a bullet">
              <Plus className="size-3.5" />
              Add
            </Toggle>
            <Toggle value="ask" aria-label="Ask or instruct the model">
              <Sparkles className="size-3.5" />
              AI
            </Toggle>
          </ToggleGroup>
          <Input
            ref={draftInputRef}
            size="sm"
            className="min-w-0 flex-1"
            placeholder={
              inputMode === "add"
                ? "Add something the summary missed"
                : "Ask about the day, or change the list"
            }
            disabled={inputMode === "ask" && (summary === null || standup.isInstructing)}
            value={draft}
            onChange={(event) => setDraft(event.target.value)}
          />
          <Button
            type="submit"
            variant="ghost"
            size="icon-sm"
            aria-label={inputMode === "add" ? "Add this item" : "Send to the model"}
            disabled={inputMode === "ask" && (summary === null || standup.isInstructing)}
          >
            {inputMode === "add" ? <Plus className="size-4" /> : <Sparkles className="size-4" />}
          </Button>
        </form>
        <Button variant="default" size="sm" disabled={keptCount === 0} onClick={() => void copy()}>
          <Copy className="size-4" />
          {copied ? "Copied" : `Copy ${keptCount} ${keptCount === 1 ? "bullet" : "bullets"}`}
        </Button>
      </div>

      <LearnDialog
        proposals={learnProposals}
        onClose={() => setLearnProposals(null)}
        onSave={async (rules) => {
          await standup.addLearnings(rules, "learned");
          setLearnProposals(null);
        }}
      />
    </div>
  );
}

/** Every proposed rule starts ticked and editable, so the user keeps the last word. */
function LearnDialog({
  proposals,
  onClose,
  onSave,
}: {
  proposals: readonly StandupLearnProposal[] | null;
  onClose: () => void;
  onSave: (rules: readonly string[]) => Promise<void>;
}) {
  const [rows, setRows] = useState<ReadonlyArray<{ text: string; checked: boolean }>>([]);
  const [seen, setSeen] = useState<readonly StandupLearnProposal[] | null>(null);
  // The dialog edits a copy of the proposals, so a new proposal list resets the draft.
  if (proposals !== seen) {
    setSeen(proposals);
    setRows((proposals ?? []).map((proposal) => ({ text: proposal.text, checked: true })));
  }
  const selected = rows.filter((row) => row.checked && row.text.trim().length > 0);

  return (
    <Dialog open={proposals !== null} onOpenChange={(open) => !open && onClose()}>
      <DialogPopup className="sm:max-w-lg">
        <DialogHeader>
          <DialogTitle>Learn from my edits</DialogTitle>
          <DialogDescription>
            {proposals !== null && proposals.length === 0
              ? "The edits on this day show nothing that would apply on another day."
              : "Keep the rules that match how you want every summary written. They go to Settings, under the daily summary prompt."}
          </DialogDescription>
        </DialogHeader>
        {proposals !== null && proposals.length > 0 ? (
          <DialogPanel>
            <div className="flex flex-col gap-3">
              {proposals.map((proposal, index) => {
                const row = rows[index];
                if (row === undefined) return null;
                return (
                  <label key={proposal.text} className="flex items-start gap-2">
                    <Checkbox
                      className="mt-1"
                      checked={row.checked}
                      onCheckedChange={(checked) =>
                        setRows((current) =>
                          current.map((entry, at) =>
                            at === index ? { ...entry, checked: checked === true } : entry,
                          ),
                        )
                      }
                    />
                    <span className="flex min-w-0 flex-1 flex-col gap-1">
                      <Input
                        size="sm"
                        aria-label="Rule text"
                        value={row.text}
                        onChange={(event) =>
                          setRows((current) =>
                            current.map((entry, at) =>
                              at === index ? { ...entry, text: event.target.value } : entry,
                            ),
                          )
                        }
                      />
                      {proposal.basis.length > 0 ? (
                        <span className="text-muted-foreground text-xs">
                          From: {proposal.basis}
                        </span>
                      ) : null}
                    </span>
                  </label>
                );
              })}
            </div>
          </DialogPanel>
        ) : null}
        <DialogFooter>
          <Button variant="ghost" size="sm" onClick={onClose}>
            {proposals !== null && proposals.length === 0 ? "Close" : "Cancel"}
          </Button>
          {proposals !== null && proposals.length > 0 ? (
            <Button
              variant="default"
              size="sm"
              disabled={selected.length === 0}
              onClick={() => void onSave(selected.map((row) => row.text.trim()))}
            >
              Save {selected.length} {selected.length === 1 ? "rule" : "rules"}
            </Button>
          ) : null}
        </DialogFooter>
      </DialogPopup>
    </Dialog>
  );
}

/**
 * One bullet. Controls show on hover, so the resting state reads as the text
 * about to be pasted. An excluded row keeps its control visible: a hidden way
 * back is no way back. Enter or blur saves an edit, Escape drops it.
 */
function StandupItemRow({
  item,
  onToggle,
  onEdit,
}: {
  item: StandupItem;
  onToggle: () => void;
  onEdit: (text: string) => void;
}) {
  const { attributes, listeners, setNodeRef, transform, transition, isDragging } = useSortable({
    id: item.itemId,
  });
  const [editing, setEditing] = useState<string | null>(null);

  const commit = () => {
    if (editing === null) return;
    onEdit(editing);
    setEditing(null);
  };

  return (
    <div
      ref={setNodeRef}
      style={{ transform: CSS.Translate.toString(transform), transition }}
      className={cn(
        "group flex items-start gap-1 rounded-md px-1 py-1 hover:bg-muted/50",
        isDragging && "z-10 bg-muted shadow-sm",
      )}
    >
      <button
        type="button"
        className={cn(
          "mt-0.5 shrink-0 cursor-grab rounded p-0.5 text-muted-foreground opacity-0 transition-opacity",
          "group-hover:opacity-100 focus-visible:opacity-100",
          isDragging && "cursor-grabbing opacity-100",
        )}
        aria-label="Reorder this item"
        {...attributes}
        {...listeners}
      >
        <GripVertical className="size-3.5" />
      </button>
      <span aria-hidden className="mt-[0.2rem] shrink-0 text-muted-foreground text-sm">
        &bull;
      </span>
      {editing !== null ? (
        <textarea
          autoFocus
          rows={1}
          className="field-sizing-content min-w-0 flex-1 resize-none rounded-md border bg-transparent px-1 py-0.5 text-sm leading-relaxed outline-none focus-visible:ring-1 focus-visible:ring-inset"
          aria-label="Edit this item"
          value={editing}
          onChange={(event) => setEditing(event.target.value)}
          onBlur={commit}
          onKeyDown={(event) => {
            if (event.key === "Enter" && !event.shiftKey) {
              event.preventDefault();
              commit();
            } else if (event.key === "Escape") {
              event.preventDefault();
              setEditing(null);
            }
          }}
        />
      ) : (
        <p
          className={cn(
            "min-w-0 flex-1 text-sm leading-relaxed",
            item.excluded && "text-muted-foreground line-through",
          )}
          onDoubleClick={() => setEditing(item.text)}
        >
          {item.text}
        </p>
      )}
      <span
        className={cn(
          "flex shrink-0 opacity-0 transition-opacity group-hover:opacity-100 has-focus-visible:opacity-100",
          editing !== null && "invisible",
        )}
      >
        <Button
          variant="ghost"
          size="icon-sm"
          aria-label="Edit this item"
          onClick={() => setEditing(item.text)}
        >
          <Pencil className="size-3.5" />
        </Button>
      </span>
      <span
        className={cn(
          "flex shrink-0 opacity-0 transition-opacity group-hover:opacity-100 has-focus-visible:opacity-100",
          item.excluded && "opacity-100",
        )}
      >
        <Button
          variant="ghost"
          size="icon-sm"
          aria-label={item.excluded ? "Put this item back" : "Leave this item out"}
          onClick={onToggle}
        >
          {item.excluded ? <Undo2 className="size-3.5" /> : <X className="size-3.5" />}
        </Button>
      </span>
    </div>
  );
}
